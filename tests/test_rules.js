'use strict';
const assert=require('node:assert/strict');
const {KharTall}=require('../engine.js');
const g=new KharTall({random:()=>0});
assert.equal(g.N,10);assert.equal(g.s.pieces.length,32);
assert.equal(g.king(0).hp,2);assert.equal(g.king(1).hp,2);
assert.equal(g.placeTrap(0,4,4),true);assert.equal(g.placeTrap(0,5,4),true);
assert.equal(g.placeTrap(0,6,4),false);assert.equal(g.finishSetup(),true);
assert.equal(g.placeTrap(1,4,4),true);assert.equal(g.finishSetup(),true);
assert.equal(g.s.phase,'play');
const original=g.snapshot();const clone=KharTall.restore(original);
assert.deepEqual(clone.snapshot(),original);
const king=g.king(0),colossus=g.s.pieces.find(p=>p.side===0&&p.type==='colossus');
const wolf=g.s.pieces.find(p=>p.side===0&&p.type==='wolf');
g.s.pieces=[king,colossus,wolf,g.king(1),g.guardian(0),g.guardian(1)];
king.x=5;king.y=5;king.hp=1;colossus.x=2;colossus.y=5;wolf.x=2;wolf.y=3;
assert.equal(g.canRescue(colossus),true);assert.equal(g.canRescue(wolf),true);
colossus.y=4;assert.equal(g.canRescue(colossus),false);colossus.y=5;
king.hp=2;assert.equal(g.canRescue(colossus),false);king.hp=1;
g.s.side=0;g.s.reaction=null;g.s.combo=null;g.s.fieldPending=null;g.s.traps=[];
const rescue=g.actionsFor(colossus.id).find(a=>a.kind==='rescue');assert.ok(rescue);
assert.equal(g.act(rescue),true);assert.equal(king.hp,1);
assert.deepEqual([king.x,king.y],[2,5]);assert.deepEqual([colossus.x,colossus.y],[5,5]);
assert.equal(king.copy.type,'colossus');
assert.ok(g.s.phase!=='over');
console.log('Rules OK: board, setup, secret traps, snapshots, Colossus/Wolf reach and cooperative rescue without king damage.');
